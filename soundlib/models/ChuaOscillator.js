// Indices into DIMENSIONLESS of the 19 "base attractors" (DSChua.py: psetbase).
const BASE_ATTRACTOR_INDICES = [0, 4, 7, 22, 32, 38, 41, 52, 56, 59, 63, 64, 74, 88, 96, 106, 115, 118, 129];

export class ChuaOscillator extends BaseSound {
    static WORKLET_PATH = new URL('../worklets/chuaProcessor.js', import.meta.url).href;

    constructor(context, name) {
        super(context, name);

        const [alpha, beta, gamma, m0, m1, mk] = DIMENSIONLESS[BASE_ATTRACTOR_INDICES[0]];

        this.addParameter('alpha', alpha, -1100, 100, 0, 0);
        this.addParameter('beta', beta, -250, 250, 0, 0);
        this.addParameter('gamma', gamma, -4, 4, 0, 0);
        this.addParameter('m0', m0, -10, 5, 0, 0);
        this.addParameter('m1', m1, -150, 5, 0, 0);
        this.addParameter('mk', mk, -1, 1, 0, 0);
        this.addParameter('tscale', 1000, 0, 100000, 0, 0);
        this.addIntegerParameter('baseAttractor', 0, 0, BASE_ATTRACTOR_INDICES.length - 1);

        this.createNodes();
    }

    createNodes() {
        if (!this.workletNode) {
            this.workletNode = new AudioWorkletNode(this.context, 'chuaProcessor', {
                processorOptions: { sampleRate: this.context.sampleRate }
            });
            this.gainNode = this.context.createGain();
            this.workletNode.connect(this.gainNode);
            this.outputNode = this.gainNode;

            this.workletNode.parameters.get('active').setValueAtTime(0, this.context.currentTime);
            this.gainNode.gain.setValueAtTime(0, this.context.currentTime);
        }
    }

    startSound() {
        if (this.workletNode) {
            this.workletNode.port.postMessage({ action: 'start' });
            this.workletNode.parameters.get('active').setValueAtTime(1, this.context.currentTime);
            this.scheduleAttack(this.gainNode);
            this.startTime = this.context.currentTime;

            ['alpha', 'beta', 'gamma', 'm0', 'm1', 'mk', 'tscale'].forEach(n => this.updateParameter(n));
        }
    }

    stopSound(onReleased) {
        this.scheduleDecay(this.gainNode, () => {
            if (this.workletNode) {
                this.workletNode.parameters.get('active').setValueAtTime(0, this.context.currentTime);
            }
            if (typeof onReleased === 'function') {
                onReleased();
            }
        });
    }

    updateParameter(name) {
        const param = this.getParameter(name);
        const now = this.context.currentTime;

        switch (name) {
            case 'alpha':
            case 'beta':
            case 'gamma':
            case 'm0':
            case 'm1':
            case 'mk':
            case 'tscale':
                if (this.workletNode) {
                    this.workletNode.parameters.get(name).setValueAtTime(param.get(), now);
                }
                break;
            case 'baseAttractor': {
                const [alpha, beta, gamma, m0, m1, mk] = DIMENSIONLESS[BASE_ATTRACTOR_INDICES[param.get()]];
                this.setParameter('alpha', alpha);
                this.setParameter('beta', beta);
                this.setParameter('gamma', gamma);
                this.setParameter('m0', m0);
                this.setParameter('m1', m1);
                this.setParameter('mk', mk);
                if (this.workletNode) {
                    this.workletNode.port.postMessage({ action: 'start' });
                }
                break;
            }
            case 'gain':
                if (this.inDecaySegment) {
                    console.log('Ignoring gain update during decay.');
                    return;
                }
                if (this.inAttackSegment) {
                    this.updateGainDuringAttack(this.gainNode, param.get(), this.startTime, param.attackTime);
                } else {
                    this.gainNode.gain.setTargetAtTime(param.get(), now, 0.05);
                }
                break;
        }
    }

    connect(destination) {
        super.connect(destination);
        if (this.gainNode && this.destination) {
            this.gainNode.connect(this.destination);
        }
    }

    disconnect() {
        if (this.gainNode && this.destination) {
            this.gainNode.disconnect(this.destination);
        }
        super.disconnect();
    }

    destroy() {
        super.destroy();
        if (this.workletNode) {
            this.workletNode.disconnect();
        }
        if (this.gainNode) {
            this.gainNode.disconnect();
        }
    }
}
